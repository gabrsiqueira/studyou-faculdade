package br.com.studyou.data.repository

import br.com.studyou.data.remote.ApiResult
import br.com.studyou.data.remote.StudYouApiClient
import br.com.studyou.domain.model.CrosswordPuzzle
import br.com.studyou.domain.model.Flashcard
import br.com.studyou.domain.model.GameSummary
import br.com.studyou.domain.model.GameType
import br.com.studyou.domain.model.GuessWordPuzzle
import br.com.studyou.domain.model.NewGameAttempt
import br.com.studyou.domain.model.QuizQuestion
import br.com.studyou.domain.model.displayTitle
import br.com.studyou.domain.model.streakDays
import br.com.studyou.domain.repository.GameRepository

/**
 * Serves the games generated by the backend for each file (held in [generatedGamesStore]) and
 * records finished games for the signed-in user on the backend (mirrored in [gameAttemptStore]).
 */
class GameRepositoryImpl(
    private val api: StudYouApiClient,
    private val generatedGamesStore: GeneratedGamesStore,
    private val gameAttemptStore: GameAttemptStore
) : GameRepository {

    override suspend fun getGames(fileId: String): List<GameSummary> {
        val games = generatedGamesStore.get(fileId) ?: return emptyList()
        val descriptions = mapOf(
            GameType.QUIZ to "Perguntas de múltipla escolha sobre o conteúdo do arquivo.",
            GameType.FLASHCARDS to "Revise os conceitos principais em cartões de memorização.",
            GameType.GUESS_WORD to "Descubra a palavra-chave em até ${games.guessWord.maxAttempts} tentativas.",
            GameType.CROSSWORD to "Toque nas letras para formar palavras e preencher as palavras cruzadas."
        )
        val attemptsForFile = gameAttemptStore.current().filter { it.fileId == fileId }

        return GameType.entries.map { type ->
            val attempts = attemptsForFile.filter { it.gameType == type }
            val best = attempts.maxByOrNull { it.scorePercent }
            GameSummary(
                type = type,
                title = type.displayTitle(),
                description = descriptions.getValue(type),
                resultLabel = if (best == null) {
                    "Ainda não jogado"
                } else {
                    "Melhor resultado: ${best.bestScoreLabel} · ${attempts.size} tentativa(s)"
                },
                played = best != null
            )
        }
    }

    override suspend fun getQuiz(fileId: String): List<QuizQuestion> =
        generatedGamesStore.get(fileId)?.quiz.orEmpty()

    override suspend fun getFlashcards(fileId: String): List<Flashcard> =
        generatedGamesStore.get(fileId)?.flashcards.orEmpty()

    override suspend fun getGuessWordPuzzle(fileId: String): GuessWordPuzzle? =
        generatedGamesStore.get(fileId)?.guessWord

    override suspend fun getCrosswordPuzzle(fileId: String): CrosswordPuzzle? =
        generatedGamesStore.get(fileId)?.crossword

    override suspend fun saveAttempt(attempt: NewGameAttempt): Result<Unit> =
        when (val result = api.saveAttempt(attempt)) {
            is ApiResult.Success -> {
                gameAttemptStore.add(result.data)
                Result.success(Unit)
            }
            is ApiResult.Failure -> Result.failure(IllegalStateException(result.message))
        }

    override suspend fun currentStreakDays(): Int =
        streakDays(gameAttemptStore.current().map { it.playedAtMillis })

    override suspend fun totalXp(): Int = gameAttemptStore.current().sumOf { it.xpEarned }
}
